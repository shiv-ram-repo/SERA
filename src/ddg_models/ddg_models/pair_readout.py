"""
pair_readout
============
Generalises the readout algebra from a rank-1 antisymmetric bilinear form to
rank r.

The standard multimodal ddG readout computes a per-amino-acid score vector
s(h) in R^21 at the mutated position and takes

    ddG = s[mut] - s[wt].

Written as a bilinear form in the one-hot vectors this is

    ddG = e_mut^T M(h) e_wt,     M(h) = s 1^T - 1 s^T,

so M is antisymmetric and of rank at most two, generated by the single vector
s. The consequence is structural: the effect of a substitution is forced to be
a difference of two per-residue energies, and no pair-specific term can exist.
G->P and G->A must differ by exactly s[P] - s[A] in every structural context,
so proline's backbone constraint, disulfide partners and charge reversal can
only be approximated by per-residue offsets. The mutant identity never
interacts with the wild-type identity; it only indexes a lookup.

The generalisation keeps exact antisymmetry while removing the rank
restriction:

    M(h) = A(h) - A(h)^T,    A(h) = U(h) V(h)^T,    U, V in R^{21 x r}
    ddG  = sum_k  U[mut,k] V[wt,k] - U[wt,k] V[mut,k].

Antisymmetry holds by construction for any U, V, because swapping wt and mut
negates the expression. The current model is the r = 1 case with U[:,0] = s and
V[:,0] = 1, so this module keeps the existing head as that first component and
adds r-1 learned columns whose projection is zero-initialised. Training
therefore starts bit-for-bit at the current architecture and any pair coupling
has to be earned.

Cost is small: a linear map from the fused representation to 2*21*(r-1)
numbers, 236K parameters at r = 4 against a 1.26M head.
"""

from __future__ import annotations

import torch
import torch.nn as nn


class PairCoupling(nn.Module):
    """Produces the extra U, V columns of the antisymmetric coupling matrix."""

    def __init__(self, input_dim: int, rank: int = 4, n_aa: int = 21,
                 hidden: int = 0) -> None:
        super().__init__()
        self.rank = max(1, int(rank))
        self.n_extra = self.rank - 1          # column 0 is the existing head
        self.n_aa = n_aa
        if self.n_extra <= 0:
            self.proj = None
            return
        out = n_aa * self.n_extra
        # Two separate projections. Zeroing BOTH factors of the product would
        # make every gradient vanish identically -- d/dU (uv) = v = 0 and
        # d/dV (uv) = u = 0 -- so the module could never leave initialisation.
        # Only V is zeroed: the product is still exactly zero at step zero, so
        # the readout matches the rank-1 baseline, while d/dV = u is non-zero so
        # training can begin. This is the same asymmetry LoRA uses.
        if hidden and hidden > 0:
            self.proj_u = nn.Sequential(
                nn.Linear(input_dim, hidden), nn.GELU(), nn.Linear(hidden, out))
            self.proj_v = nn.Sequential(
                nn.Linear(input_dim, hidden), nn.GELU(), nn.Linear(hidden, out))
            last_u, last_v = self.proj_u[-1], self.proj_v[-1]
        else:
            self.proj_u = nn.Linear(input_dim, out)
            self.proj_v = nn.Linear(input_dim, out)
            last_u, last_v = self.proj_u, self.proj_v
        nn.init.normal_(last_u.weight, std=0.02)
        if last_u.bias is not None:
            nn.init.zeros_(last_u.bias)
        nn.init.zeros_(last_v.weight)
        if last_v.bias is not None:
            nn.init.zeros_(last_v.bias)
        self.proj = self.proj_u          # kept so `self.proj is None` still works

    def forward(self, h: torch.Tensor):
        """h: (K, D) -> U_extra, V_extra each (K, 21, r-1); None if rank == 1."""
        if self.n_extra <= 0:
            return None, None
        u = self.proj_u(h).view(-1, self.n_aa, self.n_extra)
        v = self.proj_v(h).view(-1, self.n_aa, self.n_extra)
        return u, v


def pair_term(U_extra, V_extra, wt_onehot, mut_onehot):
    """sum_k U[mut,k] V[wt,k] - U[wt,k] V[mut,k] for the extra columns.

    U_extra, V_extra: (K, 21, r-1); one-hots: (K, 21). Returns (K,).
    """
    if U_extra is None:
        return None
    w = wt_onehot.unsqueeze(-1)                              # (K, 21, 1)
    m = mut_onehot.unsqueeze(-1)
    u_mut = (U_extra * m).sum(-2)                            # (K, r-1)
    u_wt = (U_extra * w).sum(-2)
    v_mut = (V_extra * m).sum(-2)
    v_wt = (V_extra * w).sum(-2)
    return (u_mut * v_wt - u_wt * v_mut).sum(-1)             # (K,)
